-- General audit log
-- event_type is the log subsystem (e.g. 'auth', 'ptt', 'ws.chat') for events
-- captured from Log(LOG_AUDIT, ...) by rrserver/audit.c, or a category such as
-- 'login', 'logout', 'kicked', 'muted', 'unmuted', 'banned' for direct calls
-- to db_add_audit_event(). username is '-' when the logger doesn't know it.
CREATE TABLE audit_log (
   id INTEGER PRIMARY KEY AUTOINCREMENT,
   timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
   username TEXT NOT NULL,
   event_type TEXT NOT NULL,
   session_id TEXT, -- non-secret 20-character session fingerprint; NULL for server-originated events
   details TEXT  -- optional, for additional info if needed
);

-- PTT-specific event log
-- vfo: VFO letter ('A'...) the user keyed; duration: seconds of TX set on
-- key-down by db_ptt_stop(). recording_id links the row to its audio file;
-- stop_reason records released, disconnect, timeout, thermal, or forced off.
CREATE TABLE ptt_log (
   id INTEGER PRIMARY KEY AUTOINCREMENT,
   username TEXT NOT NULL,
   server TEXT,
   vfo TEXT,
   frequency REAL NOT NULL,
   mode TEXT NOT NULL,
   bandwidth INTEGER NOT NULL,
   power REAL NOT NULL,
   start_time DATETIME DEFAULT CURRENT_TIMESTAMP,
   end_time DATETIME,
   duration INTEGER,
   record_file TEXT,
   recording_id TEXT,
   stop_reason TEXT,
   supervision_ticket TEXT,
   supervising_elmers TEXT
);

-- TX credit accounting: remaining TX seconds per user. One row is consumed
-- at key-down when quota.enforce is true (see rrserver/ptt.c); session
-- duration is debited on key-up. Users with no row have no credits.
CREATE TABLE tx_credits (
   name TEXT PRIMARY KEY,
   credits INTEGER NOT NULL DEFAULT 0,
   updated DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_log (
   msg_id INTEGER PRIMARY KEY AUTOINCREMENT,
   msg_ts INTEGER NOT NULL DEFAULT (unixepoch()),
   msg_src TEXT NOT NULL,
   msg_dest TEXT DEFAULT NULL,
   msg_type TEXT NOT NULL,
   msg_data TEXT NOT NULL
);

CREATE INDEX chat_log_dest_ts ON chat_log (msg_dest, msg_ts, msg_id);

-- Persistent room metadata. Chat history remains in chat_log when a room is removed.
CREATE TABLE rooms (
   name TEXT PRIMARY KEY,
   uuid TEXT NOT NULL UNIQUE DEFAULT (
      lower(hex(randomblob(4)) || '-' || hex(randomblob(2)) || '-4' ||
            substr(hex(randomblob(2)),2) || '-a' ||
            substr(hex(randomblob(2)),2) || '-' || hex(randomblob(6)))
   ),
   has_vfos INTEGER NOT NULL DEFAULT 0,
   vfo_mask INTEGER NOT NULL DEFAULT 0,
   deleted INTEGER NOT NULL DEFAULT 0,
   topic TEXT NOT NULL DEFAULT '',
   autogenerated INTEGER NOT NULL DEFAULT 0,
   startup_id TEXT DEFAULT NULL,
   created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE room_vfos (
   room TEXT NOT NULL,
   binding TEXT NOT NULL,
   created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (room, binding),
   FOREIGN KEY (room) REFERENCES rooms(name) ON DELETE CASCADE
);

-- Stable canonical identity for a configured logical rig. The readable alias
-- belongs to one node/config namespace and is not itself protocol identity.
CREATE TABLE rig_identities (
   identity_namespace TEXT NOT NULL,
   alias TEXT NOT NULL,
   uuid TEXT NOT NULL UNIQUE,
   created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY (identity_namespace, alias)
);

-- Persistent VFO identity is scoped to its owning canonical rig UUID. The
-- config_id is stable backend/config identity; display aliases may change.
CREATE TABLE vfo_identities (
   rig_uuid TEXT NOT NULL,
   config_id TEXT NOT NULL,
   uuid TEXT NOT NULL UNIQUE,
   created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
   PRIMARY KEY(rig_uuid, config_id),
   FOREIGN KEY(rig_uuid) REFERENCES rig_identities(uuid) ON DELETE CASCADE
);

-- Users
CREATE TABLE users (
   uid INTEGER PRIMARY KEY,         -- unique user ID
   name TEXT NOT NULL UNIQUE,       -- username
   enabled BOOLEAN NOT NULL,        -- 0 = disabled, 1 = enabled
   password TEXT NOT NULL,          -- hashed password
   password_set INTEGER NOT NULL DEFAULT (unixepoch()),
   password_expires INTEGER DEFAULT NULL,
   password_change_required BOOLEAN NOT NULL DEFAULT 0,
   email TEXT,                      -- optional email
   maxsessions INTEGER DEFAULT 1,   -- max allowed simultaneous sessions
   permissions TEXT                 -- comma-separated or JSON if complex
);

-- Optional Web UI password credentials. A missing row disables password login.
-- password_phc is a self-describing, salted password hash (Argon2id preferred).
-- Never place a plaintext password, SHA-1 verifier or client private key here.
-- Native client public-key enrollment is stored independently of this table.
-- Existing users.password is legacy-only until the new authentication protocol
-- and migration are ready; do not interpret it as a web_password credential.
CREATE TABLE IF NOT EXISTS user_web_credentials (
   uid INTEGER PRIMARY KEY REFERENCES users(uid) ON DELETE CASCADE,
   password_phc TEXT NOT NULL,
   updated_at INTEGER NOT NULL DEFAULT (unixepoch())
);

-- Native client key identities are independent of Web UI passwords.
-- An account may have multiple authorized devices. Revocation is per key.
-- Enrollment is an administrative action; a presented key is not trusted
-- merely because it can produce a valid signature.
CREATE TABLE IF NOT EXISTS user_public_keys (
   uid INTEGER NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
   key_id TEXT NOT NULL,
   public_key TEXT NOT NULL UNIQUE,
   label TEXT NOT NULL DEFAULT '',
   enabled BOOLEAN NOT NULL DEFAULT 1,
   created_at INTEGER NOT NULL DEFAULT (unixepoch()),
   last_used_at INTEGER,
   PRIMARY KEY(uid, key_id)
);

-- Native client bootstrap credentials. Separate from Web UI passwords and legacy
-- authentication; consumption is committed only with successful key enrollment.
-- Store only a slow salted verifier, never a plaintext enrollment secret.
CREATE TABLE IF NOT EXISTS user_key_enrollment (
   uid INTEGER PRIMARY KEY REFERENCES users(uid) ON DELETE CASCADE,
   verifier_phc TEXT NOT NULL,
   expires_at INTEGER NOT NULL,
   attempts INTEGER NOT NULL DEFAULT 0,
   created_at INTEGER NOT NULL DEFAULT (unixepoch()),
   consumed_at INTEGER
);

-- v1 scoped authorization. System-wide roles (admin, owner, etc.) remain
-- in users.permissions until core roles have a dedicated typed representation.
-- Resource grants are separate and keyed by stable resource UUID, not names.
-- Cross-site subjects are written as user@host and resolved using the linked
-- site's advertised identity, never by trusting client-supplied UUIDs.
CREATE TABLE resource_privileges (
   id INTEGER PRIMARY KEY,
   subject_user TEXT NOT NULL,
   subject_host TEXT NOT NULL DEFAULT '',
   resource_kind TEXT NOT NULL CHECK(resource_kind IN ('site','rig','vfo','room','media','serial','file','bridge')),
   resource_uuid TEXT NOT NULL,
   privilege TEXT NOT NULL,
   effect TEXT NOT NULL DEFAULT 'allow' CHECK(effect IN ('allow','deny')),
   granted_by TEXT NOT NULL,
   granted_at INTEGER NOT NULL DEFAULT (unixepoch()),
   expires_at INTEGER DEFAULT NULL,
   UNIQUE(subject_user,subject_host,resource_kind,resource_uuid,privilege)
);
CREATE INDEX resource_privileges_subject
   ON resource_privileges(subject_host,subject_user,resource_kind,resource_uuid);
CREATE INDEX resource_privileges_resource
   ON resource_privileges(resource_kind,resource_uuid,privilege);

-- Reusable collections of resource operations. A set contains privileges,
-- not subjects, allowing the same policy to be assigned many times.
CREATE TABLE privilege_sets (
   id INTEGER PRIMARY KEY,
   name TEXT NOT NULL UNIQUE COLLATE NOCASE,
   description TEXT NOT NULL DEFAULT '',
   created_by TEXT NOT NULL,
   created_at INTEGER NOT NULL DEFAULT (unixepoch()),
   CHECK(length(name) BETWEEN 1 AND 96)
);
CREATE TABLE privilege_set_entries (
   set_id INTEGER NOT NULL REFERENCES privilege_sets(id) ON DELETE CASCADE,
   privilege TEXT NOT NULL,
   effect TEXT NOT NULL DEFAULT 'allow' CHECK(effect IN ('allow','deny')),
   PRIMARY KEY(set_id,privilege),
   CHECK(length(privilege) BETWEEN 1 AND 128)
);
-- An assignment binds user@host and resource UUID to a reusable set.
-- It can expire independently of the set definition.
CREATE TABLE privilege_set_assignments (
   id INTEGER PRIMARY KEY,
   set_id INTEGER NOT NULL REFERENCES privilege_sets(id) ON DELETE CASCADE,
   subject_user TEXT NOT NULL COLLATE NOCASE,
   subject_host TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
   resource_kind TEXT NOT NULL CHECK(resource_kind IN ('site','rig','vfo','room','media','serial','file','bridge')),
   resource_uuid TEXT NOT NULL,
   assigned_by TEXT NOT NULL,
   assigned_at INTEGER NOT NULL DEFAULT (unixepoch()),
   expires_at INTEGER DEFAULT NULL,
   UNIQUE(set_id,subject_user,subject_host,resource_kind,resource_uuid)
);
CREATE INDEX privilege_set_assignments_subject
   ON privilege_set_assignments(subject_host,subject_user,resource_kind,resource_uuid);
CREATE INDEX privilege_set_assignments_resource
   ON privilege_set_assignments(resource_kind,resource_uuid);
-- Symbolic account groups survive remote node and rig UUID replacement.
CREATE TABLE user_groups (
   name TEXT PRIMARY KEY COLLATE NOCASE,
   description TEXT NOT NULL DEFAULT ''
);
CREATE TABLE user_group_members (
   group_name TEXT NOT NULL REFERENCES user_groups(name) ON DELETE CASCADE,
   subject_user TEXT NOT NULL COLLATE NOCASE,
   subject_host TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
   PRIMARY KEY(group_name,subject_user,subject_host)
);
CREATE TABLE user_group_privileges (
   group_name TEXT NOT NULL REFERENCES user_groups(name) ON DELETE CASCADE,
   resource_kind TEXT NOT NULL CHECK(resource_kind IN ('rig','room')),
   resource_name TEXT NOT NULL,
   privilege TEXT NOT NULL,
   effect TEXT NOT NULL CHECK(effect IN ('allow','deny')),
   PRIMARY KEY(group_name,resource_kind,resource_name,privilege)
);
CREATE INDEX user_group_members_identity ON user_group_members(subject_user,subject_host);
CREATE INDEX privilege_set_entries_privilege
   ON privilege_set_entries(privilege);

-- Payload-byte and frame accounting; NULL allowance means unlimited.
CREATE TABLE IF NOT EXISTS user_usage (name TEXT PRIMARY KEY COLLATE NOCASE, reset_at INTEGER NOT NULL DEFAULT (unixepoch()), tx_text_bytes INTEGER NOT NULL DEFAULT 0 CHECK(tx_text_bytes >= 0), tx_text_frames INTEGER NOT NULL DEFAULT 0 CHECK(tx_text_frames >= 0), tx_binary_bytes INTEGER NOT NULL DEFAULT 0 CHECK(tx_binary_bytes >= 0), tx_binary_frames INTEGER NOT NULL DEFAULT 0 CHECK(tx_binary_frames >= 0), rx_text_bytes INTEGER NOT NULL DEFAULT 0 CHECK(rx_text_bytes >= 0), rx_text_frames INTEGER NOT NULL DEFAULT 0 CHECK(rx_text_frames >= 0), rx_binary_bytes INTEGER NOT NULL DEFAULT 0 CHECK(rx_binary_bytes >= 0), rx_binary_frames INTEGER NOT NULL DEFAULT 0 CHECK(rx_binary_frames >= 0), session_seconds INTEGER NOT NULL DEFAULT 0 CHECK(session_seconds >= 0), tx_seconds INTEGER NOT NULL DEFAULT 0 CHECK(tx_seconds >= 0), bandwidth_remaining INTEGER, tx_reset_at INTEGER NOT NULL DEFAULT 0);

-- Validated receiver capability hints, scoped to an endpoint identity digest.
-- These describe support, never current receiver availability.
CREATE TABLE bridge_capabilities (
   identity TEXT PRIMARY KEY,
   hints TEXT NOT NULL,
   updated_at INTEGER NOT NULL
);
