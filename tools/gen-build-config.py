#!/usr/bin/env python3
"""Generate the normal build_config.h without the embedded EEPROM toolchain."""
import argparse
import json
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("profile", help="config/<profile>.config.json")
parser.add_argument("--config", help="Optional explicit build config JSON (for tests)")
parser.add_argument("--mongoose", choices=("true", "false"), required=True)
parser.add_argument("--output", required=True)
args = parser.parse_args()

config = json.loads(Path(args.config or f"config/{args.profile}.config.json").read_text())
version = Path(".version").read_text().strip()
match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)(?:-rc\d+)?", version)
if not match:
    parser.error(f"Invalid project version {version!r}")
major, minor = map(int, match.groups()[:2])
features = config.get("features", {})
backend = config.get("backend", {})
debug = config.get("debug", {})
eeprom = config.get("eeprom", {})
limits = config.get("limits", {})
database = config.get("database", {}).get("master", {})

def enabled(value):
    return str(value).lower() in ("true", "1", "yes", "on")

def quoted(value):
    return json.dumps(str(value), ensure_ascii=True)

header = [
    "/* Generated by tools/gen-build-config.py; do not edit. */",
    "#ifndef _config_h",
    "#define _config_h",
    f'#define VERSION "{major:02}.{minor:02}"',
    f"#define VERSION_MAJOR 0x{major:x}",
    f"#define VERSION_MINOR 0x{minor:x}",
    '#define HARDWARE "sb50"',
    "#define USE_RUSTYIRC 1",
]
def define(name, value=None):
    header.append(f"#define {name}" if value is None else f"#define {name} {value}")

i2c_addr = config.get("i2c", {}).get("myaddr")
if i2c_addr is not None:
    define("MY_I2C_ADDR", i2c_addr)

for field, macro in (
    ("max_amps", "RR_MAX_AMPS"),
    ("max_atus", "RR_MAX_ATUS"),
    ("max_filters", "RR_MAX_FILTERS"),
    ("rf_talk_timeout", "RF_TALK_TIMEOUT"),
):
    if field in limits:
        define(macro, limits[field])
for field, macro in (("path", "MASTERDB_PATH"), ("template", "MASTERDB_TEMPLATE")):
    if field in database:
        define(macro, quoted(database[field]))

for field, macro in (
    ("alsa", "USE_ALSA"),
    ("coredumps-client", "USE_COREDUMPS_CLIENT"),
    ("coredumps-fwdsp", "USE_COREDUMPS_FWDSP"),
    ("coredumps-server", "USE_COREDUMPS_SERVER"),
    ("debug-build", "DEBUG_BUILD"),
    ("gstreamer", "USE_GSTREAMER"),
    ("libnotify", "USE_LIBNOTIFY"),
    ("mqtt", "USE_MQTT"),
    ("opus", "USE_OPUS"),
    ("flac", "USE_FLAC"),
    ("pipewire", "USE_PIPEWIRE"),
    ("sqlite", "USE_SQLITE"),
):
    if enabled(features.get(field)):
        define(macro)
for field, macro in (("cat-kpa500", "CAT_KPA500"), ("cat-yaesu", "CAT_YAESU")):
    if enabled(features.get(field)):
        define(macro, "true")
if args.mongoose == "true":
    define("USE_MONGOOSE")
if enabled(backend.get("hamlib")):
    define("USE_HAMLIB")

hamlib_debug = backend.get("hamlib_debug", backend.get("hamlib-debug", "warn"))
levels = {"bug": "BUG", "err": "ERR", "warn": "WARN", "verbose": "VERBOSE",
          "trace": "TRACE", "cache": "CACHE"}
define("BACKEND_HAMLIB_DEBUG", "RIG_DEBUG_" + levels.get(hamlib_debug, "NONE"))
for field, macro in (
    ("hamlib-model", "BACKEND_HAMLIB_MODEL"),
    ("hamlib-baud", "BACKEND_HAMLIB_BAUD"),
):
    if field in backend:
        define(macro, backend[field])
if "hamlib-port" in backend:
    define("BACKEND_HAMLIB_PORT", quoted(backend["hamlib-port"]))

if enabled(debug.get("profiling", features.get("profiling"))):
    define("USE_PROFILING", "true")
if "logfile" in debug:
    define("LOG_FILE", quoted(debug["logfile"]))
if enabled(debug.get("noisy-eeprom")):
    define("NOISY_EEPROM", "true")
if args.mongoose == "true" and enabled(debug.get("mongoose")):
    define("MONGOOSE_DEBUG", "true")

http = config.get("net", {}).get("http", {})
if enabled(http.get("enabled")):
    if "authdb" in http:
        define("HTTP_AUTHDB_PATH", quoted(http["authdb"]))
    if enabled(http.get("authdb_dynamic")):
        define("HTTP_AUTHDB_DYNAMIC", 1)

if "size" in eeprom:
    define("EEPROM_SIZE", int(eeprom["size"]))
define("MAX_BANDS", int(features.get("max-bands", features.get("max_bands", 10))))
if config.get("build", {}).get("platform") == "posix":
    define("HOST_CAT_PIPE", '"cat.fifo"')
    define("HOST_POSIX")
    define("HOST_LINUX")
    define("HTTP_USE_TLS", 1)
    define("HTTP_TLS_KEY", '"./config/key.pem"')
    define("HTTP_TLS_CERT", '"./config/cert.pem"')
header.append("#endif /* _config_h */")
out = Path(args.output)
out.parent.mkdir(parents=True, exist_ok=True)
content = "\n".join(header) + "\n"
# Don't force recompilation unless the header actually changed.
if not out.is_file() or out.read_text() != content:
    out.write_text(content)
