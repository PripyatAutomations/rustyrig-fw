#!/usr/bin/env python3
"""Generate native/browser privilege catalogs from authoritative C access checks.

This is a lexical scan, not a C preprocessor: all build profiles are included.
Run from any directory; --check reports stale generated files without writing.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
COMPONENTS = ('rrserver', 'rrclient', 'librrprotocol', 'librustyaxe', 'libfwdspmgr', 'rrbridge', 'fwdsp')
CHECKS = {'has_priv', 'match_priv', 'media_have_priv', 'userlist_priv', 'privilege', 'user_privilege_contains'}
TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*.*?\*/', re.S)
STRING = re.compile(r'"(?:\\.|[^"\\])*"')


def scan():
    found = {}
    for component in COMPONENTS:
        for path in sorted((ROOT / component).rglob('*')):
            if path.is_symlink() or path.suffix not in {'.c', '.h'} or any(
                    part in {'tests', 'ext', 'build', '.git'} for part in path.parts):
                continue
            if '.generated.' in path.name:
                continue
            source = path.read_text(errors='replace')
            code = TOKEN.sub(lambda m: re.sub(r'[^\n]', ' ', m[0]) if m[0].startswith('/') else m[0], source)
            # Mask strings too, so delimiters and check names inside literals cannot count as code.
            masked = TOKEN.sub(lambda m: re.sub(r'[^\n]', ' ', m[0]), code)
            calls = re.finditer(r'\b(' + '|'.join(sorted(CHECKS)) + r')\s*\(', masked)
            ranges = []
            for call in calls:
                depth, pos, argument = 1, call.end(), call.end()
                while pos < len(masked) and depth:
                    char = masked[pos]
                    if char == '(':
                        depth += 1
                    elif char == ')':
                        depth -= 1
                    elif char == ',' and depth == 1:
                        argument = pos + 1
                    pos += 1
                if not depth:
                    ranges.append((argument, pos - 1))
            # Runtime serial export permissions are constructed with snprintf.
            for call in re.finditer(r'\bsnprintf\s*\(\s*privileges?\s*,', masked):
                end = masked.find(';', call.end())
                if end >= 0:
                    ranges.append((call.end(), end))
            for start, end in ranges:
                for literal in STRING.finditer(code, start, end):
                    try:
                        text = json.loads(literal[0])
                    except ValueError:
                        continue
                    for name in re.split(r'[|,]', text.replace('%s', '*')):
                        if not re.fullmatch(r'[a-z][a-z0-9_.-]*(?:\*)?', name):
                            continue
                        location = f'{path.relative_to(ROOT)}:{source.count(chr(10), 0, literal.start()) + 1}'
                        found.setdefault(name, set()).add(location)
    return {name: sorted(sources) for name, sources in sorted(found.items())}



def registry():
    entries = json.loads((ROOT / 'res/privileges.json').read_text())
    for name, info in entries.items():
        if not re.fullmatch(r'[a-z][a-z0-9_.-]*\*?', name):
            raise ValueError(f'Invalid privilege token: {name}')
        if not isinstance(info, dict) or any(not isinstance(info.get(k), str) or not info[k].strip()
                                            for k in ('label', 'description', 'scope')):
            raise ValueError(f'Missing privilege metadata: {name}')
        if info['scope'] not in ('system', 'resource'):
            raise ValueError(f'Invalid privilege scope: {name}')
    return entries


def native_header(entries):
    lines = ['// Generated by tools/generate-privileges.py; do not edit.',
             '#ifndef RRCLIENT_PRIVILEGES_GENERATED_H', '#define RRCLIENT_PRIVILEGES_GENERATED_H',
             'typedef struct { const char *name, *label, *description, *scope; } rr_privilege_info_t;',
             'static const rr_privilege_info_t rrclient_privilege_registry[] = {']
    for name, info in sorted(entries.items()):
        lines.append('   {' + ', '.join(json.dumps(field) for field in
                     (name, info['label'], info['description'], info['scope'])) + '},')
    lines += ['};', 'static const char *const rrclient_known_privileges[] = {']
    lines += ['   ' + json.dumps(name) + ',' for name in sorted(entries)]
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = scan()
    entries = registry()
    missing = sorted(set(catalog) - set(entries))
    if missing:
        parser.exit(1, 'Unregistered privileges: ' + ', '.join(missing) + '\n')
    names = sorted(entries)
    outputs = {
        ROOT / 'rrclient/privileges.generated.h': native_header(entries),
        ROOT / 'doc/privileges.generated.json': json.dumps(catalog, indent=2) + '\n',
    }
    browser = ROOT / 'www/js/webui.privileges.generated.js'
    if browser.parent.is_dir():
        outputs[browser] = ('// Generated by tools/generate-privileges.py; do not edit.\n'
                            'const rrKnownPrivileges = ' + json.dumps(names) + ';\n'
                            'const rrPrivilegeRegistry = ' + json.dumps(entries, indent=2) + ';\n')
    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(content)
    if args.check and stale:
        parser.exit(1, 'Stale privilege catalogs: ' + ', '.join(stale) + '\n')
    print(f'{len(names)} privileges: ' + ', '.join(names))


if __name__ == '__main__':
    main()
