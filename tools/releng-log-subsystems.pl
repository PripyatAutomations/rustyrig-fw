#!/usr/bin/env perl
# Generate a compile-time catalog from literal Log(priority, "subsystem", ...)
# calls. Names built dynamically at runtime are deliberately not guessed.
use strict;
use warnings;
use File::Find;

my %names;
find({ no_chdir => 1, wanted => sub {
    return unless -f $_ && /\.c$/;
    my $path = $File::Find::name;
    return if $path =~ m{/(?:tests?|ext|build|win32)/};
    open my $fh, '<', $path or die "$path: $!";
    local $/;
    my $src = <$fh>;
    close $fh;
    # Only literal subsystem names. We do not execute or eval source code.
    while ($src =~ /\bLog\s*\(\s*[^,()]+\s*,\s*"([A-Za-z0-9_.:*\/-]+)"/g) {
        $names{$1} = 1;
    }
}}, grep { -d $_ } qw(rrclient rrserver rrbridge fwdsp libfwdspmgr rrpipelines));

print "/* Generated by tools/releng-log-subsystems.pl; do not edit. */\n";
print "#ifndef RR_LOG_SUBSYSTEMS_GENERATED_H\n#define RR_LOG_SUBSYSTEMS_GENERATED_H\n";
print "static const char *const rr_log_subsystems[] = {\n";
for my $name (sort keys %names) {
    print qq(   "$name",\n);
}
print "   NULL\n};\n#endif\n";
