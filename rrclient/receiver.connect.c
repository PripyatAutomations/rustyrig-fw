static struct {
   char *profile, *request, *room, *payload, *url;
   bool release;
   rrconn_t *connection;
   uint64_t started;
   bool save;
} pending;
static rr_event_token_t result_token, close_token, joined_token, removed_token;
static unsigned serial;
static GHashTable *connected_receivers;
/* Room identity is the lifecycle owner of a temporary receiver. */
static GHashTable *receiver_rooms;
static char *receiver_key(const char *profile, const char *url) {
   return g_strdup_printf("%s\n%s", profile ? profile : "", url ? url : "");
}
bool rrclient_receiver_is_connected(const char *url) {
   rrconn_t *connection = rrclient_active_connection();
   const char *profile = connection ? rrclient_connection_name(connection) : NULL;

   if (!connected_receivers || !profile || !url) {
      return false;
   }
   char *key = receiver_key(profile, url);
   bool found = g_hash_table_contains(connected_receivers, key);
   g_free(key);

   return found;
}

static void clear_pending(void) {
   g_free(pending.profile);
   g_free(pending.request);
   g_free(pending.room);
   g_free(pending.payload);
   g_free(pending.url);
   memset(&pending, 0, sizeof(pending));
}
static void report(const char *message, rrconn_t *connection) {
   ui_print(NULL, "%s", message);
   event_emit("client.receiver-directory.connection", connection, message);
}
static bool send_receiver_request(rrconn_t *connection) {
   if (!pending.payload || !connection || pending.connection != connection) {
      return false;
   }
   dict *message = dict_new();

   if (!message) {
      return false;
   }
   dict_add(message, "msg.type", "talk");
   dict_add(message, "talk.cmd", "admin");
   dict_add(message, "talk.action", pending.release ? "websdr-disconnect" : pending.save ? "websdr-add" : "websdr-connect");
   dict_add(message, "talk.data", pending.payload);
   bool sent = ws_send_dict(NULL, connection, message, WEBSOCKET_OP_TEXT);
   dict_free(message);

   if (!sent) {
      clear_pending();
   }
   report(sent ? "SDR stage 2/3: request sent; awaiting server authorization and receiver backend response…" : "SDR request transport failed: unable to send the command to the selected server.", connection);

   return sent;
}

static void join_receiver(void *data);
static void receiver_room_joined(const char *event, const char *room, rrconn_t *connection, void *unused) {
   (void)event;
   (void)unused;

   if (!pending.room || !room || strcasecmp(pending.room, room) || connection != pending.connection || !pending.request) {
      return;
   }

   if (mono_us() - pending.started >= 15000000) {
      report("SDR room JOIN timed out after 15 seconds; receiver attachment was not sent. Verify room permissions, server connection, and JOIN response.", connection);
      clear_pending();

      return;
   }
   g_clear_pointer(&pending.room, g_free);
   send_receiver_request(connection);
}
bool rrclient_receiver_connect_room_ex(const char *url, bool save, const char *room, bool autogenerated) {
   const receiver_directory_entry_t *receiver = receiver_directory_find_url(url);
   rrconn_t *connection = rrclient_active_connection();
   const char *profile = connection ? rrclient_connection_name(connection) : NULL;

   if (!connection || !connection->is_ws || !connection->authenticated) {
      report("SDR connection cannot start: select an authenticated RustyRig server (WebSocket connection required).", connection);

      return false;
   }

   if (!save && !autogenerated && (!room || !*room || !ws_room_name_valid(room))) {
      report("SDR connection not sent: no valid listening room specified. Choose Create new room or select an existing room.", connection);
      return false;
   }
   if (!save && autogenerated && room && *room) {
      report("SDR connection not sent: autogenerated room names are assigned by the server.", connection);
      return false;
   }

   if (receiver && !receiver_directory_entry_accessible(receiver)) {
      report("SDR preflight rejected: directory reports this receiver as restricted, unavailable, or without published API permission.", connection);

      return false;
   }

   if (pending.request && mono_us() - pending.started < 15000000) {
      report("SDR request blocked: a previous room JOIN or receiver attachment is still pending.", connection);

      return false;
   }
   clear_pending();
   char id[48];
   snprintf(id, sizeof(id), "receiver-%u", ++serial);
   dict *fields = dict_new();
   dict_add(fields, "url", receiver ? receiver->url : url);
   dict_add(fields, "driver", receiver ? receiver->driver : "kiwi");
   dict_add(fields, "request", id);

   /* Directory information is descriptive, not an authorization source. The server records actual initiator and request time itself. */
   if (receiver) {
      const char *names[] = {
         "name", "location", "country", "contact", "antenna", "hardware", "grid"
      };
      const char *values[] = {
         receiver->name, receiver->location, receiver->country,
         receiver->contact, receiver->antenna, receiver->hardware, receiver->grid
      };

      for (unsigned i = 0 ; i < G_N_ELEMENTS(names) ; i++) {
         if (values[i] && *values[i]) {
            char key[48];
            snprintf(key, sizeof(key), "directory.%s", names[i]);
            dict_add(fields, key, values[i]);
         }
      }

      /* A directory entry's public description is a useful initial SDR
       * topic, but never an authorization statement. */
      if (receiver->description && *receiver->description)
         dict_add(fields, "directory.description", receiver->description);
      else if (receiver->name && *receiver->name)
         dict_add(fields, "directory.description", receiver->name);
      char number[48];
      snprintf(number, sizeof(number), "%d", receiver->users);
      dict_add(fields, "directory.users", number);
      snprintf(number, sizeof(number), "%d", receiver->users_max);
      dict_add(fields, "directory.users_max", number);
      snprintf(number, sizeof(number), "%llu", (unsigned long long)receiver->low_hz);
      dict_add(fields, "directory.low_hz", number);
      snprintf(number, sizeof(number), "%llu", (unsigned long long)receiver->high_hz);
      dict_add(fields, "directory.high_hz", number);
      snprintf(number, sizeof(number), "%lld", receiver->last_seen);
      dict_add(fields, "directory.last_seen", number);
   }

   if (!save) {
      if (autogenerated) dict_add_bool(fields, "room.autogenerated", true);
      else if (room && *room) dict_add(fields, "room", room);
   }
   pending.profile = g_strdup(profile);
   pending.url = g_strdup(receiver ? receiver->url : url);
   pending.request = g_strdup(id);
   pending.connection = connection;
   pending.started = mono_us();
   pending.save = save;
   pending.payload = dict2json(fields);
   dict_free(fields);

   if (!pending.payload) {
      clear_pending();

      return false;
   }

   /* Generated SDR rooms are created and bound by the server on success.
    * Never JOIN them speculatively: failures must leave no phantom room.
    * Existing rooms require membership, which the server checks as well. */
   if (!save && !autogenerated && room && *room && !rrclient_room_is_joined(room)) {
      report("SDR attachment not sent: join the selected existing room first, or choose Create new room.", connection);
      clear_pending();
      return false;
   }
   return send_receiver_request(connection);
}
bool rrclient_receiver_disconnect(const char *url) {
   rrconn_t *connection = rrclient_active_connection();
   const char *profile = connection ? rrclient_connection_name(connection) : NULL;

   if (!connection || !connection->authenticated || !url || !rrclient_receiver_is_connected(url)) {
      return false;
   }

   if (pending.request && mono_us() - pending.started < 15000000) {
      return false;
   }
   clear_pending();
   char id[48];
   snprintf(id, sizeof(id), "receiver-%u", ++serial);
   dict *fields = dict_new();

   if (!fields) {
      return false;
   }
   dict_add(fields, "url", url);
   dict_add(fields, "driver", "kiwi");
   dict_add(fields, "request", id);
   pending.profile = g_strdup(profile);
   pending.request = g_strdup(id);
   pending.url = g_strdup(url);
   pending.connection = connection;
   pending.started = mono_us();
   pending.release = true;
   pending.payload = dict2json(fields);
   dict_free(fields);

   return send_receiver_request(connection);
}
bool rrclient_receiver_connect_room(const char *url, bool save, const char *room) {
   return rrclient_receiver_connect_room_ex(url, save, room, false);
}
bool rrclient_receiver_connect(const char *url, bool save) {
   return rrclient_receiver_connect_room_ex(url, save, NULL, false);
}
static void join_receiver(void *data) {
   char *args[] = {
      (char *)"join", data
   };
   cmd_join(2, args);
}
static void receiver_result(const char *event, const char *text, rrconn_t *connection, void *unused) {
   (void)event;
   (void)unused;

   if (pending.request && mono_us() - pending.started >= 15000000) {
      char status[384];
      snprintf(status, sizeof(status),
         "SDR timeout: no server result for %s on %s within 15 seconds; check bridge initialization, server logs and permissions.",
         pending.url ? pending.url : "(unknown receiver)",
         pending.profile ? pending.profile : "(unknown server)");
      report(status, pending.connection);
      clear_pending();
      return;
   }

   if (!pending.request || pending.connection != connection || rrclient_connection_find(pending.profile) != connection) {
      return;
   }
   dict *message = text ? json2dict(text) : NULL;

   if (!message || strcmp(dict_get(message, "talk.action", ""), "websdr-result")) {
      dict_free(message);

      return;
   }
   dict *result = json2dict(dict_get(message, "talk.data", ""));

   if (result && !strcmp(dict_get(result, "request", ""), pending.request)) {
      const char *error = dict_get(result, "error", ""), *room = dict_get(result, "room", "");

      if (*error) {
         /* The server may have already retired a failed temporary receiver.
          * Its stale Directory entry is not an active connection. */
         if (pending.release && strstr(error, "No temporary SDR connection owned by this operator")) {
            char *key = receiver_key(pending.profile, pending.url);
            if (connected_receivers) g_hash_table_remove(connected_receivers, key);
            if (receiver_rooms) {
               GHashTableIter iter;
               gpointer room_key, mapped_key;
               g_hash_table_iter_init(&iter, receiver_rooms);
               while (g_hash_table_iter_next(&iter, &room_key, &mapped_key))
                  if (!strcmp(mapped_key, key)) g_hash_table_iter_remove(&iter);
            }
            g_free(key);
            report("SDR receiver was already removed by the server; cleared stale connection state.", connection);
         } else {
            char detail[640];
            snprintf(detail, sizeof(detail), "SDR server rejected %s for %s: %s",
               pending.release ? "disconnect" : pending.save ? "configuration save" : "receiver attachment",
               pending.url ? pending.url : "(unknown receiver)", error);
            report(detail, connection);
         }
      } else if (pending.release && dict_get_bool(result, "disconnected", false)) {
         char *key = receiver_key(pending.profile, pending.url);

         /* The server also broadcasts room-removed, but its notification can
          * arrive before/after this response. Close locally on ACK as a
          * fallback; duplicate removal is already safe in the room handler. */
         GPtrArray *closing = g_ptr_array_new_with_free_func(g_free);
         if (receiver_rooms) {
            GHashTableIter rooms;
            gpointer room_name, mapped_key;
            g_hash_table_iter_init(&rooms, receiver_rooms);
            while (g_hash_table_iter_next(&rooms, &room_name, &mapped_key)) {
               if (!strcmp(mapped_key, key) &&
                   g_str_has_prefix((const char *)room_name, "#sdr-")) {
                  g_ptr_array_add(closing, g_strdup(room_name));
               }
            }
         }
         for (guint i = 0; i < closing->len; i++) {
            const char *closing_room = g_ptr_array_index(closing, i);
            dict *removed = dict_new();
            if (removed) {
               dict_add(removed, "talk.room", closing_room);
               dict_add(removed, "talk.user", "server");
               char *payload = dict2json(removed);
               if (payload) {
                  event_emit("room.deleted", connection, payload);
                  free(payload);
               }
               dict_free(removed);
            }
         }
         g_ptr_array_free(closing, TRUE);

         if (connected_receivers) {
            g_hash_table_remove(connected_receivers, key);
         }
         if (receiver_rooms) {
            GHashTableIter iter;
            gpointer room_key, mapped_key;
            g_hash_table_iter_init(&iter, receiver_rooms);
            while (g_hash_table_iter_next(&iter, &room_key, &mapped_key))
               if (!strcmp(mapped_key, key)) g_hash_table_iter_remove(&iter);
         }
         g_free(key);
         report("SDR disconnected: the server acknowledged receiver release.", connection);
      } else if (pending.save) {
         report("SDR configuration saved on server; receiver is not connected yet.", connection);
      } else if (ws_room_name_valid(room) && connection->authenticated) {
         if (!connected_receivers) {
            connected_receivers = g_hash_table_new_full(g_str_hash, g_str_equal, g_free, NULL);
         }
         char *key = receiver_key(pending.profile, pending.url);
         g_hash_table_add(connected_receivers, g_strdup(key));
         if (!receiver_rooms) receiver_rooms = g_hash_table_new_full(g_str_hash, g_str_equal, g_free, g_free);
         g_hash_table_replace(receiver_rooms, g_strdup(room), key);

         if (!rrclient_room_is_joined(room)) {
            report("SDR stage 3/3: receiver attached; joining the bound room now…", connection);
            rrclient_connection_dispatch(connection, join_receiver, (void *)room);
         }
         char status[320];
         snprintf(status, sizeof(status),
            "SDR attached to %s. Awaiting room VFO announcement; select the room tab for RX controls. Audio starts on demand.",
            room);
         report(status, connection);
      }
      clear_pending();
   }
   dict_free(result);
   dict_free(message);
}
static void receiver_room_removed(const char *event, const char *data, rrconn_t *connection, void *unused) {
   (void)event; (void)unused;
   dict *message = data ? json2dict(data) : NULL;
   const char *room = message ? dict_get(message, "talk.room", NULL) : NULL;
   if (room && receiver_rooms) {
      gpointer real_key = NULL, value = NULL;
      if (g_hash_table_lookup_extended(receiver_rooms, room, &real_key, &value)) {
         if (connected_receivers) g_hash_table_remove(connected_receivers, value);
         g_hash_table_remove(receiver_rooms, room);
         event_emit("client.receiver-directory.connection", connection,
            "SDR receiver removed; its room and connection have been released.");
      }
   }
   if (message) dict_free(message);
}
static void receiver_closed(const char *event, const char *data, rrconn_t *connection, void *unused) {
   (void)event;
   (void)data;
   (void)unused;

   if (pending.connection == connection) {
      clear_pending();
   }

   if (connected_receivers) {
      g_hash_table_remove_all(connected_receivers);
   }
   if (receiver_rooms) g_hash_table_remove_all(receiver_rooms);
   event_emit("client.receiver-directory.connection", connection, "Server disconnected.");
}
void rrclient_receiver_connect_init(void) {
   result_token = event_on_token("admin.result", receiver_result, NULL);
   close_token = event_on_token("disconnected", receiver_closed, NULL);
   joined_token = event_on_token("client.room.joined", receiver_room_joined, NULL);
   removed_token = event_on_token("room.deleted", receiver_room_removed, NULL);
}
void rrclient_receiver_connect_shutdown(void) {
   if (result_token) {
      event_off_token(result_token);
   }

   if (close_token) {
      event_off_token(close_token);
   }

   if (joined_token) {
      event_off_token(joined_token);
   }
   if (removed_token) event_off_token(removed_token);
   result_token = close_token = joined_token = removed_token = 0;
   clear_pending();
   g_clear_pointer(&connected_receivers, g_hash_table_unref);
   g_clear_pointer(&receiver_rooms, g_hash_table_unref);
}
